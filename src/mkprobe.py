#!/usr/bin/env python3
"""
Hardware build A: turn the CURRENT mlfull.py into a receive probe.

Boots, brings up OUR RS-232 exactly as the real client does (same serini,
same nmih, same timing table), waits ~4 s for the radio to come up, then
three times: clear the ring, send APP_START, wait 4 s, and print what our
receiver assembled. A good reply starts 3E xx 00 05 (SELF_INFO). The verdict
line is computed on the C64, so a photo of the screen is the whole report.

  python3 mkprobe.py [src=mlfull.py] [out=mlprobe.py]
  python3 mlprobe.py 7 out.prg 0 0 <latadj>
"""
import io, sys

src = sys.argv[1] if len(sys.argv) > 1 else "mlfull.py"
dst = sys.argv[2] if len(sys.argv) > 2 else "mlprobe.py"
s = io.open(src, encoding="utf-8").read()


def rep(old, new):
    global s
    n = s.count(old)
    assert n == 1, "anchor found %d times: %r" % (n, old[:70])
    s = s.replace(old, new)


rep('''        jsr serini

        jsr bootinf
''', '''        jsr serini
        jsr prb_run             ; PROBE BUILD: three exchanges, then halt
prb_halt: jmp prb_halt
''')

ROUTINE = '''
; ===== receive probe (generated by mkprobe.py) ==========================
prb_run:
        lda #30                 ; green
        jsr CHROUT
        lda #<prb_t1
        sta PTR
        lda #>prb_t1
        sta PTRH
        jsr prtstr
; the timing in use: bit period, then first-sample delay
        lda bthi
        jsr hexout
        lda btlo
        jsr hexout
        lda #32
        jsr CHROUT
        lda hbhi
        jsr hexout
        lda hblo
        jsr hexout
        lda #13
        jsr CHROUT
; the radio boots with the cart: give it time before the first word
        lda #255
        sta prb_n
prb_b:  jsr wait1
        dec prb_n
        bne prb_b
        lda #0
        sta prb_t
        sta prb_ok
prb_try:
        lda #0
        sta RHEAD
        sta RTAIL
        sta STATE
        sta READY
        sta FRERR
        lda #<pyastart
        sta PTR
        lda #>pyastart
        sta PTRH
        lda #11
        jsr setpay
        jsr sendfr
        lda #240
        sta prb_n
prb_w:  jsr wait1
        dec prb_n
        bne prb_w
        lda #5                  ; white
        jsr CHROUT
        lda #<prb_t2
        sta PTR
        lda #>prb_t2
        sta PTRH
        jsr prtstr
        lda prb_t
        clc
        adc #49
        jsr CHROUT
        lda #<prb_t3
        sta PTR
        lda #>prb_t3
        sta PTRH
        jsr prtstr
        lda RHEAD
        jsr hexout
        lda #<prb_t4
        sta PTR
        lda #>prb_t4
        sta PTRH
        jsr prtstr
        lda FRERR
        jsr hexout
        lda #13
        jsr CHROUT
        lda #0
        sta prb_n
prb_l:  ldx prb_n
        lda RBUF,x
        jsr hexout
        lda #32
        jsr CHROUT
        inc prb_n
        lda prb_n
        cmp #12
        bcc prb_l
        lda #13
        jsr CHROUT
; look for 3e xx 00 05 ANYWHERE in the ring: an unsolicited push (a mesh
; packet log, say) can arrive ahead of the reply and must not fail the try
        lda RHEAD
        cmp #4
        bcs prb_big
        jmp prb_bad
prb_big: sec
        sbc #3
        sta prb_m
        ldx #0
prb_s:  lda RBUF,x
        cmp #62
        bne prb_nx
        lda RBUF+2,x
        bne prb_nx
        lda RBUF+3,x
        cmp #5
        beq prb_hit
prb_nx: inx
        cpx prb_m
        bcc prb_s
prb_bad: lda #28                ; red
        jsr CHROUT
        lda #<prb_fl
        sta PTR
        lda #>prb_fl
        sta PTRH
        jsr prtstr
        jmp prb_vd
prb_hit: stx prb_x
        inc prb_ok
        lda #30
        jsr CHROUT
        lda #<prb_ps
        sta PTR
        lda #>prb_ps
        sta PTRH
        jsr prtstr
        lda prb_x
        jsr hexout
        lda #13
        jsr CHROUT
prb_vd: inc prb_t
        lda prb_t
        cmp #3
        bcs prb_dn
        jmp prb_try
prb_dn: lda #158                ; yellow
        jsr CHROUT
        lda #<prb_t5
        sta PTR
        lda #>prb_t5
        sta PTRH
        jsr prtstr
        lda prb_ok
        jsr hexout
        lda #<prb_t6
        sta PTR
        lda #>prb_t6
        sta PTRH
        jsr prtstr
        rts
prb_n:  .byte 0
prb_t:  .byte 0
prb_ok: .byte 0
prb_m:  .byte 0
prb_x:  .byte 0
prb_t1: .text "rx probe 2.3.4d  bt/hb: "
        .byte 0
prb_t2: .text "try "
        .byte 0
prb_t3: .text "  n="
        .byte 0
prb_t4: .text " fe="
        .byte 0
prb_t5: .text "good replies (of 3): "
        .byte 0
prb_t6: .text "  want 3e xx 00 05"
        .byte 13,0
prb_ps: .text "PASS  selfinfo at offset "
        .byte 0
prb_fl: .text "FAIL  not a selfinfo header"
        .byte 13,0

'''
rep('wait1:  lda JIFFY', ROUTINE + 'wait1:  lda JIFFY')
io.open(dst, "w", encoding="utf-8").write(s)
print("wrote", dst)
